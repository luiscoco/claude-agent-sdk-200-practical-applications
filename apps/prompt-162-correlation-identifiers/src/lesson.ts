import { randomUUID } from 'node:crypto';
import { native, requireNative, report } from './native.js';
import { eventLog } from './observability.js';
import { mcpFixture } from './mcp-fixture.js';
export async function run(mode: string) {
  const requestId = randomUUID(), config = await mcpFixture();
  const observed = await native(mode === 'live' ? 'Call classroom policy and report its retry limit.' : 'Owned correlation baseline.', {
    mcpServers: { classroom: config }, allowedTools: ['mcp__classroom__policy'],
  }, mode === 'live');
  requireNative(observed, mode !== 'live'); const logs = eventLog(requestId, observed.events);
  const calls = logs.flatMap(row => row.toolCalls), results = logs.flatMap(row => row.toolResults);
  return report({ requestId, sessionId: observed.sessionId, logs, correlatedTools: calls.map(call => ({ ...call, matchingResults: results.filter(r => r.toolUseId === call.id) })) }, {
    rootRequestMapsToActualSdkSession: logs.some(row => row.requestId === requestId && row.sessionId === observed.sessionId),
    ...(mode === 'live' ? { actualToolCallAndResultJoined: calls.length > 0 && calls.every(call => results.some(r => r.toolUseId === call.id)) } : {}),
  }, { nativeSuccess: observed.success }, 'The application request ID is generated by the host. SDK session, tool-use, parent-tool-use and agent identifiers come from actual events; missing child activity is not replaced with synthetic spans.');
}
