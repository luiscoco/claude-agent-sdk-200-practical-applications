const byId = (id) => document.getElementById(id);
let lastReport;
let selectedIndex = 0;
function element(tag, text) {
  const node = document.createElement(tag);
  node.textContent = text;
  return node;
}
async function source(file = 'src/agent.ts') {
  const response = await fetch('/api/source?file=' + encodeURIComponent(file));
  if (!response.ok) throw new Error('Source unavailable.');
  const data = await response.json();
  byId('source-title').textContent = data.file;
  byId('files').replaceChildren();
  byId('source').replaceChildren();
  for (const name of data.files) {
    const button = element('button', name);
    button.className = 'secondary';
    button.onclick = () => source(name);
    byId('files').append(button);
  }
  data.content.split('\n').forEach((line, index) => {
    const row = element('span', line || ' ');
    row.className = 'code-line';
    row.dataset.line = index + 1;
    byId('source').append(row);
  });
}
async function showView(name) {
  document
    .querySelectorAll('.view')
    .forEach((view) => view.classList.toggle('hidden', view.id !== name + '-view'));
  document
    .querySelectorAll('[data-view]')
    .forEach((button) => button.classList.toggle('active', button.dataset.view === name));
  if (name === 'source') await source();
}
document
  .querySelectorAll('[data-view]')
  .forEach((button) => (button.onclick = () => showView(button.dataset.view)));
function error(message) {
  byId('error').textContent = message;
  byId('error').classList.toggle('hidden', !message);
}
function showSelected() {
  byId('facts').textContent =
    'Actual SDK query · capture native init and result session identifiers\nClassroom case · ' +
    byId('mode').selectedOptions[0].textContent +
    '\nFixture topic · ' +
    byId('topic').value +
    '\nThe application conversation ID is generated by this host. The SDK session ID comes from native messages.\nOnly a successful validated native query creates a persisted conversation mapping.';
}
function resetResult() {
  lastReport = undefined;
  for (const id of ['preapproved-value', 'hook-value', 'approval-value', 'read-value'])
    byId(id).textContent = '—';
  for (const id of ['request', 'admission', 'result', 'checks', 'evidence', 'metadata'])
    byId(id).textContent = 'Awaiting this actual native failure experiment.';
  byId('download').classList.add('hidden');
  byId('download').removeAttribute('href');
  byId('conversation-select').replaceChildren();
  byId('lookup').disabled = true;
  byId('lookup-result').textContent = 'No conversation record selected.';
  byId('rebind-evidence').textContent = 'Awaiting a verified paired capture.';
}
function showRecord() {
  const record = lastReport?.records[selectedIndex],
    observed = lastReport?.observations[selectedIndex];
  byId('request').textContent = JSON.stringify(
    {
      applicationConversationId: observed?.conversationId ?? null,
      actualInitSessionId: observed?.initIds[0] ?? null,
      actualResultSessionId: observed?.resultIds[0] ?? null,
      nativeIdentityValid: observed?.nativeIdentityValid ?? false,
    },
    null,
    2,
  );
  byId('admission').textContent = JSON.stringify(
    record
      ? {
          applicationConversationId: record.conversationId,
          persistedSdkSessionId: record.sdkSessionId,
          topic: record.topic,
          createdAt: record.createdAt,
        }
      : { recordPersisted: false },
    null,
    2,
  );
  byId('result').textContent = JSON.stringify(
    {
      actualSummary: record?.summary ?? null,
      diskReadBackMatches: record
        ? lastReport.readBack[selectedIndex]?.sdkSessionId === record.sdkSessionId
        : false,
      actualWrongRebindRejected: lastReport?.rebindControl?.rejected ?? null,
    },
    null,
    2,
  );
}
async function lookupCurrent() {
  const record = lastReport?.records[selectedIndex];
  if (!record) return;
  const response = await fetch('/api/conversation/' + encodeURIComponent(record.conversationId));
  if (!response.ok) throw new Error('Persisted conversation unavailable.');
  const persisted = await response.json();
  byId('lookup-result').textContent = JSON.stringify(persisted, null, 2);
  return persisted;
}
function display(report) {
  lastReport = report;
  byId('mode').value = report.requestedInput.mode;
  byId('topic').value = report.requestedInput.topic;
  showSelected();
  selectedIndex = 0;
  byId('preapproved-value').textContent = report.observations.length;
  byId('hook-value').textContent = report.observations.filter(
    (observation) => observation.nativeIdentityValid,
  ).length;
  byId('approval-value').textContent = report.records.length;
  byId('read-value').textContent =
    report.output.wrongRebindRejected === null
      ? 'Not requested'
      : report.output.wrongRebindRejected
        ? 'Rejected'
        : 'Failed';
  byId('conversation-select').replaceChildren();
  report.records.forEach((record, index) => {
    const option = element('option', record.label);
    option.value = index;
    byId('conversation-select').append(option);
  });
  byId('lookup').disabled = !report.records.length;
  byId('lookup-result').textContent = report.records.length
    ? 'Select a captured application record and load it from disk.'
    : 'No verified conversation was persisted.';
  showRecord();
  byId('checks').textContent = JSON.stringify(report.checks, null, 2);
  byId('rebind-evidence').textContent = JSON.stringify(report.rebindControl ?? { tested: false, reason: 'Single conversation capture.' }, null, 2);
  byId('evidence').textContent = JSON.stringify(
    {
      actualSdkObservations: report.observations,
      persistedReadBack: report.readBack,
      actualRebindControl: report.rebindControl,
    },
    null,
    2,
  );
  byId('metadata').textContent = JSON.stringify(
    {
      runId: report.id,
      nativeSessionIds: report.records.map((record) => record.sdkSessionId),
      checkedAt: report.checkedAt,
    },
    null,
    2,
  );
  byId('status').textContent = report.verified
    ? 'Native session capture and mapping verified'
    : 'Verification failed';
  byId('status').className = 'badge ' + (report.verified ? 'passed' : 'mismatch');
  byId('progress').textContent =
    'Compare native init/result identifiers, application record identity and persisted lookup.';
  byId('download').href = '/api/report/' + report.id;
  byId('download').classList.remove('hidden');
  error(report.error || (!report.verified ? 'Inspect the actual native checks.' : ''));
}
async function restore(id) {
  const response = await fetch('/api/report/' + encodeURIComponent(id));
  if (!response.ok) throw new Error('Observed session-capture report unavailable.');
  const report = await response.json();
  display(report);
  return report;
}
byId('inspect').onclick = async () => {
  for (const id of ['inspect', 'mode', 'topic']) byId(id).disabled = true;
  error('');
  resetResult();
  byId('status').textContent = 'Running actual SDK queries and capturing session IDs';
  byId('status').className = 'badge';
  try {
    const response = await fetch('/api/run', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ mode: byId('mode').value, topic: byId('topic').value }),
    });
    const report = await response.json();
    if (!response.ok) throw new Error(report.error || 'Native session-capture experiment failed.');
    display(report);
  } catch (failure) {
    error(failure.message);
    byId('status').textContent = 'Request failed';
  } finally {
    for (const id of ['inspect', 'mode', 'topic']) byId(id).disabled = false;
  }
};
byId('mode').onchange = showSelected;
byId('topic').onchange = showSelected;
byId('conversation-select').onchange = () => {
  selectedIndex = Number(byId('conversation-select').value);
  showRecord();
};
byId('lookup').onclick = () => lookupCurrent().catch((failure) => error(failure.message));
window.lesson = { showView, source, restore, lookupCurrent, report: () => lastReport };
for (const id of ['request', 'admission', 'result', 'checks', 'evidence', 'metadata'])
  byId(id).textContent = 'Awaiting the actual native rewrite experiment.';
showSelected();
